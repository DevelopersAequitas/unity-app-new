<?php

declare(strict_types=1);

namespace Tests\Feature;

use App\Leader\Models\LeaderReport;
use App\Models\Circle;
use App\Models\District;
use App\Models\User;
use Illuminate\Support\Str;
use Tests\TestCase;

class LeaderReportDownloadTest extends TestCase
{
    public function test_get_download_link_returns_valid_download_url(): void
    {
        $mockPerm = $this->createMock(\App\Leader\Services\LeaderPermissionService::class);
        $mockPerm->method('isLeader')->willReturn(true);
        $this->app->instance(\App\Leader\Services\LeaderPermissionService::class, $mockPerm);

        $user = new User(['id' => (string) Str::uuid()]);
        $reportId = (string) Str::uuid();

        $response = $this->actingAs($user, 'sanctum')
            ->getJson("/api/v1/leader/reports/{$reportId}/download");

        $response->assertStatus(200)
            ->assertJsonPath('success', true)
            ->assertJsonPath('data.report_id', $reportId)
            ->assertJsonStructure([
                'success',
                'data' => [
                    'report_id',
                    'file_name',
                    'file_format',
                    'file_size',
                    'download_url',
                    'expires_in_seconds',
                ],
            ]);

        $downloadUrl = $response->json('data.download_url');
        $this->assertStringContainsString("/api/v1/files/{$reportId}/download?type=pdf", $downloadUrl);
    }

    public function test_opening_download_url_returns_rendered_pdf_stream(): void
    {
        $reportId = (string) Str::uuid();

        // Access the exact download_url format generated by the reports service
        $response = $this->get("/api/v1/files/{$reportId}/download?type=pdf");

        $response->assertStatus(200);
        $response->assertHeader('Content-Type', 'application/pdf');
        $this->assertStringContainsString('inline; filename="Report-', (string) $response->headers->get('Content-Disposition'));

        // Verify PDF magic bytes
        $content = $response->getContent();
        $this->assertStringStartsWith('%PDF-', $content);
    }

    public function test_opening_download_url_for_persisted_leader_report(): void
    {
        $reportId = '2a03b39e-2e35-4e7b-aa0d-95a6098275ea';

        $response = $this->get("/api/v1/files/{$reportId}/download?type=pdf");

        $response->assertStatus(200);
        $response->assertHeader('Content-Type', 'application/pdf');

        $content = $response->getContent();
        $this->assertStringStartsWith('%PDF-', $content);
    }
}
